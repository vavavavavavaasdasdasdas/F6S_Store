package com.example.demodatn.service;

import com.example.demodatn.TestDatabaseGuard;
import com.example.demodatn.dto.khachhang.CustomerDto;
import com.example.demodatn.dto.nhanvien.EmployeeDto;
import com.example.demodatn.entity.khachhang.Customer;
import com.example.demodatn.entity.nhanvien.Employee;
import com.example.demodatn.repository.khachhang.CustomerRepository;
import com.example.demodatn.repository.nhanvien.EmployeeRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.test.context.support.WithMockUser;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.context.WebApplicationContext;

import static org.hamcrest.Matchers.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.security.test.web.servlet.setup.SecurityMockMvcConfigurers.springSecurity;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@SpringBootTest
class AutoCodeGenerationIntegrationTest {

    @Autowired PeopleService people;
    @Autowired EmployeeRepository employees;
    @Autowired CustomerRepository customers;
    @Autowired JdbcTemplate jdbc;
    @Autowired WebApplicationContext context;

    MockMvc mvc;

    @BeforeEach
    void setup() {
        TestDatabaseGuard.check(jdbc);
        mvc = MockMvcBuilders.webAppContextSetup(context).apply(springSecurity()).build();
    }

    @Test
    @Transactional
    void employeeCodeAutoIncrementsCorrectly() {
        String code1 = people.nextEmployeeCode();
        assertNotNull(code1);
        assertTrue(code1.startsWith("NV"), "Mã nhân viên phải có tiền tố NV");
        assertTrue(code1.matches("NV\\d{5}"), "Mã nhân viên định dạng NV0000x: " + code1);

        // Tạo DTO nhân viên mới để trống employeeCode
        EmployeeDto dto = new EmployeeDto();
        dto.setEmployeeCode(null);
        dto.setFullName("Nhân Viên Tự Tăng 1");
        dto.setPhone("0988776655");
        dto.setEmail("nv_autotest1@example.com");
        dto.setPosition("Nhân viên");
        dto.setUsername("nv_autotest1");
        dto.setPassword("NhanVien123");
        dto.setAddress("Hà Nội");

        Employee saved = people.saveEmployee(dto);
        assertNotNull(saved.getEmployeeCode());
        assertEquals(code1, saved.getEmployeeCode(), "Employee mới phải được tự động gán mã tự tăng");

        // Gọi tiếp nextEmployeeCode phải ra mã tiếp theo
        String code2 = people.nextEmployeeCode();
        assertNotEquals(code1, code2);
        assertTrue(code2.matches("NV\\d{5}"));
    }

    @Test
    @Transactional
    void customerCodeAutoIncrementsCorrectly() {
        String code1 = people.nextCustomerCode();
        assertNotNull(code1);
        assertTrue(code1.startsWith("KH"), "Mã khách hàng phải có tiền tố KH");
        assertTrue(code1.matches("KH\\d{5}"), "Mã khách hàng định dạng KH0000x: " + code1);

        int provId = jdbc.queryForObject("SELECT TOP 1 id FROM tinh_thanh ORDER BY id", Integer.class);
        int wardId = jdbc.queryForObject("SELECT TOP 1 id FROM phuong_xa WHERE tinh_thanh_id=? ORDER BY id", Integer.class, provId);

        // Tạo DTO khách hàng mới để trống customerCode
        CustomerDto dto = new CustomerDto();
        dto.setCustomerCode("");
        dto.setFullName("Khách Hàng Tự Tăng 1");
        dto.setPhone("0977665544");
        dto.setEmail("kh_autotest1@example.com");
        dto.setAddress("Đà Nẵng");
        dto.setProvinceId(provId);
        dto.setWardId(wardId);
        dto.setStreetAddress("123 Đường Tự Tăng");

        Customer saved = people.saveCustomer(dto);
        assertNotNull(saved.getCustomerCode());
        assertEquals(code1, saved.getCustomerCode(), "Customer mới phải được tự động gán mã tự tăng");

        // Gọi tiếp nextCustomerCode phải ra mã tiếp theo
        String code2 = people.nextCustomerCode();
        assertNotEquals(code1, code2);
        assertTrue(code2.matches("KH\\d{5}"));
    }

    @Test
    @WithMockUser(username = "admin", roles = "ADMIN")
    void createFormHasAutoGeneratedCodeInModel() throws Exception {
        mvc.perform(get("/admin/employees/create"))
                .andExpect(status().isOk())
                .andExpect(model().attribute("employee", hasProperty("employeeCode", startsWith("NV"))))
                .andExpect(content().string(containsString("id=\"employeeCode\"")))
                .andExpect(content().string(containsString("readonly")));

        mvc.perform(get("/admin/customers/create"))
                .andExpect(status().isOk())
                .andExpect(model().attribute("customer", hasProperty("customerCode", startsWith("KH"))))
                .andExpect(content().string(containsString("id=\"customerCode\"")))
                .andExpect(content().string(containsString("readonly")));
    }
}
